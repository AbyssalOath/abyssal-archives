#!/bin/bash
set -e # exit immediately if any command fails, rather than plowing ahead

# Installs (or re-runs safely on) a file hosting site. Every prompt is
# skipped when its answer is already recorded in .env, so re-running only
# rebuilds and restarts the containers.

cd "$(dirname "$0")"
# shellcheck source=scripts/lib/env.sh
source scripts/lib/env.sh
# shellcheck source=scripts/lib/qbittorrent.sh
source scripts/lib/qbittorrent.sh
# shellcheck source=scripts/lib/seeder-setup.sh
source scripts/lib/seeder-setup.sh

echo "=== File Hosting Site Installer ==="

# The container user that owns uploaded/imported files (see Dockerfile).
APP_UID=10001
APP_GID=10001

# --- Check prerequisites ---
if ! command -v docker &> /dev/null; then
        echo "Docker is not installed. Install Docker first: https://docs.docker.com/engine/install/"
        exit 1
fi

if ! docker compose version &> /dev/null; then
        echo "Docker Compose plugin is not available. Install it before continuing."
        exit 1
fi

if ! command -v openssl &> /dev/null; then
        echo "openssl is required to generate secrets. Install it before continuing."
        exit 1
fi

# --- Port availability helper ---
# port_in_use (scripts/lib/env.sh) is needed below both for the database's
# host-side port (DATABASE_URL is generated as part of .env, so this has to
# run before that) and again further down for HTTP_PORT.

# --- Generate .env if it doesn't exist ---
if [ -f .env ]; then
        echo ".env already exists -- skipping secret generation (existing install detected)."
        # Refuse to leave secrets readable by other users.
        if [ "$(stat -c '%a' .env)" != "600" ]; then
                chmod 600 .env
                echo "WARNING: .env was readable by other users; permissions fixed to 600."
                echo "If other people have access to this machine, rotate the secrets in it."
        fi
else
        echo "Generating secrets..."
        MARIADB_ROOT_PASSWORD=$(openssl rand -hex 24)
        MARIADB_PASSWORD=$(openssl rand -hex 24)

        # --- Host port (database) ---
        # MariaDB is bound to 127.0.0.1 only (see docker-compose.yml) so host-side
        # tooling (backups, cargo run) can reach it without exposing it to the
        # network; only the host-side port is configurable, in case 3306 is
        # already taken by another MySQL/MariaDB instance on this machine.
        # Resolved here, before .env generation, since DATABASE_URL needs it.
        default_db_port=3306
        while port_in_use "$default_db_port"; do
                default_db_port=$((default_db_port + 1))
        done
        if [ "$default_db_port" != "3306" ]; then
                echo ""
                echo "Port 3306 already looks taken on this machine (another MySQL/MariaDB?)."
        fi
        echo ""
        read -rp "Host port to expose MariaDB on [default: ${default_db_port}]: " db_port
        db_port=${db_port:-$default_db_port}

        cat > .env << EOF
# Generated by install.sh -- see .env.example for what every variable does.
MARIADB_ROOT_PASSWORD=${MARIADB_ROOT_PASSWORD}
MARIADB_DATABASE=filehost
MARIADB_USER=filehost
MARIADB_PASSWORD=${MARIADB_PASSWORD}
DB_PORT=${db_port}
DATABASE_URL=mysql://filehost:${MARIADB_PASSWORD}@127.0.0.1:${db_port}/filehost
EOF

        chmod 600 .env # restrict readability to the owning user only
        echo ".env generated with strong random secrets."
fi

# --- Defaults for settings this .env doesn't have yet ---
# New installs get them all; existing installs get only what newer versions
# added. Existing values are never changed.
ensure_default() {
        if ! env_has "$1"; then
                env_set "$1" "$2"
                added_defaults="${added_defaults} $1"
        fi
}
added_defaults=""
ensure_default STORAGE_BACKEND local
ensure_default STORAGE_PATH /data/storage
ensure_default INCOMING_PATH /data/incoming
ensure_default IMPORT_MIN_AGE_SECS 30
ensure_default ALLOW_WEB_UPLOAD true
ensure_default MAX_UPLOAD_BYTES 90000000
ensure_default ALLOW_REGISTRATION false
ensure_default TORRENT_ENABLED false
ensure_default TORRENT_TRACKERS ""
ensure_default TORRENT_PIECE_LENGTH 4194304
ensure_default TORRENT_DHT_ENABLED false
ensure_default MIRROR_DISCOVERY_ENABLED false
ensure_default FEDERATION_ENABLED false
ensure_default SIGN_CHECKSUMS false
ensure_default STRIP_METADATA false
ensure_default QBT_USERNAME admin
ensure_default QBT_WEBUI_PORT 8081
ensure_default QBT_CONFIG_HOST_PATH ./data/qbittorrent
# Security settings (safe defaults; docs/SECURITY-REVIEW.md, .env.example).
ensure_default SESSION_IDLE_TIMEOUT_MINS 30
ensure_default SESSION_ABSOLUTE_TIMEOUT_HOURS 12
ensure_default TOTP_ENABLED false
ensure_default TRUSTED_PROXIES "127.0.0.0/8,::1/128,172.16.0.0/12"
ensure_default CLIENT_IP_HEADER x-forwarded-for
ensure_default ADMIN_ALLOWED_CIDRS ""
ensure_default ADMIN_HOST ""
ensure_default HSTS_ENABLED false
ensure_default HSTS_INCLUDE_SUBDOMAINS false
ensure_default LOG_IP_MODE truncated
ensure_default IMPORT_CONCURRENCY 1
ensure_default STORAGE_MIN_FREE_BYTES 1G
ensure_default DOWNLOAD_MAX_PER_IP 4
ensure_default RATE_LIMIT_PER_MINUTE 600
ensure_default VERIFY_PROXY_URL ""
ensure_default APP_MEMORY_LIMIT 1g
ensure_default APP_CPUS 2
# MariaDB gets no host port unless DB_PUBLISH=true (then the override file
# publishes it on 127.0.0.1:DB_PORT for host tools).
if ! env_has DB_PUBLISH; then
        env_set DB_PUBLISH false
        added_defaults="${added_defaults} DB_PUBLISH"
        if env_has DB_PORT; then
                echo "Note: MariaDB is no longer published on the host (DB_PUBLISH=false). Set"
                echo "DB_PUBLISH=true in .env and re-run ./install.sh if you need host access to it."
        fi
fi
if [ "$(env_get DB_PUBLISH)" = "true" ] && ! env_has COMPOSE_FILE; then
        env_set COMPOSE_FILE "docker-compose.yml:docker-compose.db-publish.yml"
fi
# Key for encrypting TOTP secrets: generated once, never replaced (that
# would make enrolled authenticators unusable).
if [ -z "$(env_get TOTP_ENCRYPTION_KEY)" ]; then
        env_set TOTP_ENCRYPTION_KEY "$(openssl rand -base64 32)"
        added_defaults="${added_defaults} TOTP_ENCRYPTION_KEY"
fi
# /setup is only useful until the admin exists; turn it off for good once
# one does (checked against the running database on re-runs).
if ! env_has SETUP_ENABLED || [ "$(env_get SETUP_ENABLED)" = "true" ]; then
        admins="$(docker compose exec -T mariadb sh -c 'MYSQL_PWD="$MARIADB_PASSWORD" mariadb -N -u"$MARIADB_USER" "$MARIADB_DATABASE" -e "SELECT COUNT(*) FROM users"' 2>/dev/null || true)"
        if [ -n "$admins" ] && [ "$admins" -gt 0 ] 2>/dev/null; then
                env_set SETUP_ENABLED false
                echo "An administrator exists: SETUP_ENABLED=false (/setup is disabled for good)."
        elif ! env_has SETUP_ENABLED; then
                env_set SETUP_ENABLED true
                added_defaults="${added_defaults} SETUP_ENABLED"
        fi
fi
if [ -n "$added_defaults" ]; then
        echo "Added default values to .env for:${added_defaults}"
fi

# --- Site name ---
# Required, no default: the site has no built-in name. It is copied into the
# database at every start until it is changed in /admin/settings.
if env_has SITE_NAME; then
        echo "Site name already recorded in .env -- skipping prompt."
else
        echo ""
        site_name=""
        while [ -z "$site_name" ] || [ "${#site_name}" -gt 100 ]; do
                read -rp "Site name (shown in the header, page titles and footer): " site_name
                if [ "${#site_name}" -gt 100 ]; then
                        echo "Please keep it to 100 characters or fewer."
                fi
        done
        env_set SITE_NAME "$(env_quote "$site_name")"
        echo ""
        echo "To change the site name later, either:"
        echo "  - edit it at /admin/settings (takes effect immediately), or"
        echo "  - run: scripts/set-site-name.sh \"New Name\"   then: docker compose up -d app"
        echo "    (a name saved in /admin/settings wins over .env; see the script's --reset-override)"
fi

# --- Tagline ---
if env_has SITE_TAGLINE; then
        echo "Tagline already recorded in .env -- skipping prompt."
else
        echo ""
        read -rp "Tagline (optional, shown under the site name; blank for none): " site_tagline
        env_set SITE_TAGLINE "$(env_quote "$site_tagline")"
fi

# --- Docker project name ---
# Prefixes the container, image and volume names, so several sites can share
# one host. Defaults to the slugified site name.
if env_has COMPOSE_PROJECT_NAME; then
        echo "Docker project name already recorded in .env -- skipping prompt."
else
        default_project="$(slugify "$(env_get SITE_NAME)")"
        while true; do
                echo ""
                read -rp "Docker project name [default: ${default_project}]: " project_name
                project_name=${project_name:-$default_project}
                if [[ "$project_name" =~ ^[a-z0-9][a-z0-9_-]*$ ]]; then
                        break
                fi
                echo "Use lowercase letters, digits, '-' and '_' only, starting with a letter or digit."
        done
        env_set COMPOSE_PROJECT_NAME "$project_name"
fi

# --- Storage and incoming folders on the host ---
# Bind-mounted into the container (see docker-compose.yml).
#   storage:  only the app writes here -> owned by the container user.
#   incoming: you copy files in AND the app moves them out, so both need to
#             write: owned by you, group = the container user's group, mode
#             2775 (setgid keeps that group on everything copied in).
if ! env_has STORAGE_HOST_PATH; then
        env_set STORAGE_HOST_PATH ./data/storage
fi
if ! env_has INCOMING_HOST_PATH; then
        env_set INCOMING_HOST_PATH ./data/incoming
fi
storage_host_path="$(env_get STORAGE_HOST_PATH)"
incoming_host_path="$(env_get INCOMING_HOST_PATH)"
mkdir -p "$storage_host_path" "$incoming_host_path"
host_uid="$(id -u)"

ownership_ok() {
        [ "$(stat -c '%u:%g' "$storage_host_path")" = "${APP_UID}:${APP_GID}" ] \
                && [ "$(stat -c '%g' "$incoming_host_path")" = "${APP_GID}" ] \
                && [ "$(stat -c '%a' "$incoming_host_path")" = "2775" ]
}
fix_ownership_cmd="sudo chown -R ${APP_UID}:${APP_GID} '${storage_host_path}' \\
    && sudo chown ${host_uid}:${APP_GID} '${incoming_host_path}' && sudo chmod 2775 '${incoming_host_path}'"
if ! ownership_ok; then
        # Works as root, or with passwordless sudo; otherwise retried through
        # Docker after the image is built (see "Build and start").
        { chown -R "${APP_UID}:${APP_GID}" "$storage_host_path" \
                && chown "${host_uid}:${APP_GID}" "$incoming_host_path" \
                && chmod 2775 "$incoming_host_path"; } 2>/dev/null \
                || { sudo -n chown -R "${APP_UID}:${APP_GID}" "$storage_host_path" \
                        && sudo -n chown "${host_uid}:${APP_GID}" "$incoming_host_path" \
                        && sudo -n chmod 2775 "$incoming_host_path"; } 2>/dev/null \
                || true
fi

# Data directories must not be writable by everyone.
for dir in "$storage_host_path" "$incoming_host_path" "$(env_get QBT_CONFIG_HOST_PATH)"; do
        if [ -d "$dir" ] && [ $(( 0$(stat -c '%a' "$dir") & 2 )) -ne 0 ]; then
                echo "WARNING: $dir is world-writable. Fix it: chmod o-w '$dir'"
        fi
done

# Existing Caddyfiles are never rewritten; point out the Server header.
if [ -f Caddyfile ] && ! grep -q -- '-Server' Caddyfile; then
        echo "Hint: add 'header -Server' inside the site block of ./Caddyfile to stop"
        echo "Caddy from announcing itself (then: docker compose restart caddy)."
fi

# --- Host port (web) ---
# The container always listens on 8080 internally; only the host-side
# mapping is configurable (docker-compose.yml's HTTP_PORT), in case
# something else on this machine already has 8080.
if env_has HTTP_PORT; then
        http_port="$(env_get HTTP_PORT)"
        echo "Host port already recorded in .env (${http_port}) -- skipping prompt."
else
        default_port=8080
        while port_in_use "$default_port"; do
                default_port=$((default_port + 1))
        done
        if [ "$default_port" != "8080" ]; then
                echo ""
                echo "Port 8080 already looks taken on this machine."
        fi
        echo ""
        read -rp "Host port to expose the site on [default: ${default_port}]: " http_port
        http_port=${http_port:-$default_port}
        env_set HTTP_PORT "$http_port"
fi

# --- Compose profiles ---
# Assembled from the choices below in one variable and written to .env ONCE
# (e.g. "caddy,seeder"). Existing installs start from their current value.
profiles="$(env_get COMPOSE_PROFILES)"
profiles_before="$profiles"
add_profile() {
        profiles="$(profiles_add "$profiles" "$1")"
}

# Writes the Caddyfile, backing up an existing one instead of silently
# replacing user edits.
write_caddyfile() {
        if [ -f Caddyfile ]; then
                local backup
                backup="Caddyfile.bak.$(date +%Y%m%d%H%M%S)"
                cp Caddyfile "$backup"
                echo "Existing Caddyfile backed up to ${backup}."
        fi
        printf '%s\n' "$1" > Caddyfile
}

# --- Reverse proxy setup ---
caddyfile_written=0
if env_has PUBLIC_URL || env_has COMPOSE_PROFILES; then
        echo "Reverse proxy choice already recorded in .env -- skipping prompt."
else
        echo ""
        echo "Do you already have a reverse proxy in front of this host"
        echo "(NGINX Proxy Manager, Cloudflare Tunnel, Traefik, etc.)?"
        echo "  1) Yes -- I'll point my own proxy at it"
        echo "  2) No -- set one up for me (Caddy, automatic TLS)"
        echo "  3) No -- I'm just testing locally for now, skip HTTPS"
        read -rp "Choice [1/2/3]: " proxy_choice

        if [ "$proxy_choice" = "3" ]; then
                env_set COOKIE_SECURE false
                env_set APP_HTTP_BIND 0.0.0.0
                public_base_url="http://localhost:${http_port}"
                env_set PUBLIC_URL "$public_base_url"
                echo ""
                echo "Skipping HTTPS/reverse proxy. Once containers are up, the site is"
                echo "reachable directly at ${public_base_url}."
                echo "Set up a reverse proxy (or Caddy) before using this for anything"
                echo "beyond local testing -- the admin login should only ever travel over TLS."
        elif [ "$proxy_choice" = "2" ]; then
                echo ""
                read -rp "Domain name pointing at this server (leave blank if none / using a bare IP): " domain

                if [ -n "$domain" ]; then
                        write_caddyfile "# Written by install.sh. Caddy obtains a Let's Encrypt certificate for this
# domain automatically (ports 80 and 443 must be reachable from the internet).
${domain} {
    header -Server
    reverse_proxy app:8080
}"
                        echo "Caddyfile written for domain '${domain}' -- Caddy will obtain a real cert automatically via Let's Encrypt."
                        public_base_url="https://${domain}"
                else
                        # No public DNS, so no Let's Encrypt: use Caddy's own internal
                        # CA ("tls internal"). default_sni makes Caddy pick this
                        # certificate even when the browser sends no SNI (it doesn't
                        # for a bare IP).
                        # TODO: an app-managed private CA (stable root, renewal and
                        # rotation from the admin UI, a downloadable /ca.crt) would
                        # make trusting this easier; deliberately not ported yet.
                        default_access_host="$(hostname -I 2>/dev/null | awk '{print $1}')"
                        echo ""
                        read -rp "Hostname or IP you'll reach this server at [default: ${default_access_host:-localhost}]: " access_host
                        access_host="${access_host:-${default_access_host:-localhost}}"
                        write_caddyfile "# Written by install.sh for internal (no public domain) access, using Caddy's
# internal CA. Browsers warn until that CA's root certificate is trusted.
{
    default_sni ${access_host}
}

${access_host} {
    tls internal
    header -Server
    reverse_proxy app:8080
}"
                        echo "Caddyfile written for internal access at https://${access_host}"
                        echo ""
                        echo "WARNING: browsers will NOT trust this certificate until you import Caddy's"
                        echo "root CA. After the containers are up, export it with:"
                        echo "  docker compose exec caddy cat /data/caddy/pki/authorities/local/root.crt > caddy-root.crt"
                        echo "and import caddy-root.crt as a trusted root on each client (see README)."
                        public_base_url="https://${access_host}"
                fi
                caddyfile_written=1

                add_profile caddy
                env_set COOKIE_SECURE true
                env_set PUBLIC_URL "$public_base_url"
                # Behind Caddy the app must NOT be reachable over plain HTTP from
                # the network: Caddy talks to it over the internal Docker network,
                # and COOKIE_SECURE is on, so a browser hitting the app's own
                # http://<ip>:${http_port} directly would have its Secure session
                # cookie dropped and loop the login. Bind that port to localhost
                # only; all real traffic goes through Caddy's HTTPS on 443.
                env_set APP_HTTP_BIND 127.0.0.1
        else
                env_set COOKIE_SECURE true
                env_set APP_HTTP_BIND 0.0.0.0
                echo ""
                read -rp "Public HTTPS URL your existing reverse proxy serves the site at (e.g. https://files.example.com): " public_base_url
                public_base_url="${public_base_url%/}"
                env_set PUBLIC_URL "$public_base_url"
                host_ip="$(hostname -I 2>/dev/null | awk '{print $1}')"
                echo ""
                echo "Point your existing reverse proxy's upstream at:"
                echo "  http://${host_ip:-<this-host-ip>}:${http_port}"
                echo "and make sure it terminates HTTPS on the browser-facing side and sends"
                echo "X-Forwarded-For / X-Forwarded-Proto (NGINX Proxy Manager and cloudflared do)."
                echo "Browser uploads are only for small files; large files go through the"
                echo "incoming folder (see the end of this script and docs/IMPORT.md)."
        fi
fi

# --- Download base URL (optional) ---
if env_has DOWNLOAD_BASE_URL; then
        echo "Download base URL already recorded in .env -- skipping prompt."
else
        echo ""
        echo "Separate download hostname/base URL? (e.g. https://dl.example.com)"
        echo "Leave blank to serve downloads from the same address as the site."
        while true; do
                read -rp "Download base URL: " download_base_url
                if download_base_url="$(normalize_base_url "$download_base_url")"; then
                        break
                fi
                echo "Use http:// or https:// with a host name (and optional port), no path."
        done
        env_set DOWNLOAD_BASE_URL "$download_base_url"
        if [ -n "$download_base_url" ]; then
                echo "Point that hostname at this same app (see README: 'A separate download hostname')."
        fi
fi

# --- External sharing ---
# All off by default. The toggles can be changed later in /admin/settings;
# the seeder (option 3) adds two containers and needs a VPN account.
if env_has EXTERNAL_MIRRORS_ENABLED; then
        echo "External sharing choice already recorded in .env -- skipping prompt."
        echo "(To turn the VPN seeder on or off later: scripts/enable-seeder.sh / scripts/disable-seeder.sh)"
else
        echo ""
        echo "External sharing:"
        echo "  1) None (default) -- only this site serves files"
        echo "  2) Admin-curated mirrors/torrent links (Archive.org, GitHub, other servers)"
        echo "     -- links only, no extra containers"
        echo "  3) Self-seeding through a VPN container (ADVANCED, experimental, see docs/TORRENTS.md)"
        echo "     -- includes 2"
        read -rp "Choice [1/2/3, default 1]: " sharing_choice
        if [ "$sharing_choice" = "3" ]; then
                # Warning + typed "yes" (scripts/lib/seeder-setup.sh).
                if ! seeder_confirm; then
                        echo "Not confirmed -- enabling admin-curated mirrors only (option 2)."
                        sharing_choice=2
                fi
        fi
        if [ "$sharing_choice" = "2" ] || [ "$sharing_choice" = "3" ]; then
                env_set EXTERNAL_MIRRORS_ENABLED true
        else
                env_set EXTERNAL_MIRRORS_ENABLED false
        fi
        if [ "$sharing_choice" = "3" ]; then
                # Shared with scripts/enable-seeder.sh (scripts/lib/seeder-setup.sh).
                seeder_prompt_vpn
                seeder_ensure_password
                # The Web UI port must not collide with the site's HTTP port.
                seeder_choose_webui_port install "$http_port"
                add_profile seeder
        fi
fi

# Seeder installs (new or existing): pre-seed qBittorrent's config once.
if profiles_has "$profiles" seeder; then
        seeder_write_config
fi

if ! env_has COMPOSE_PROFILES || [ "$profiles" != "$profiles_before" ]; then
        env_set COMPOSE_PROFILES "$profiles"
        echo "COMPOSE_PROFILES set to '${profiles}'."
fi

# --- Build and start ---
echo ""
echo "Building and starting containers..."
docker compose build
if ! ownership_ok; then
        # No root/sudo here, but Docker can do it: a one-off root container
        # (MariaDB image: it has a shell, the distroless app image does not).
        echo "Setting folder ownership for the container user via Docker..."
        docker compose run --rm --no-deps --user 0 --entrypoint sh \
                -v "$(cd "$storage_host_path" && pwd):/s" -v "$(cd "$incoming_host_path" && pwd):/i" mariadb -c \
                "chown -R ${APP_UID}:${APP_GID} /s && chown ${host_uid}:${APP_GID} /i && chmod 2775 /i" \
                < /dev/null > /dev/null 2>&1 || true
fi
if ! ownership_ok; then
        echo ""
        echo "WARNING: could not give the container user (${APP_UID}:${APP_GID}) access to the"
        echo "storage and incoming folders. Run this, then: docker compose up -d"
        echo "  ${fix_ownership_cmd}"
fi
seeder_up_failed=0
case ",${profiles}," in
*",seeder,"*)
        # With the seeder, qBittorrent waits for gluetun to be healthy (VPN
        # connected). Wrong VPN settings must not abort the install: the site
        # itself still starts.
        if ! docker compose up -d; then
                seeder_up_failed=1
        fi
        ;;
*) docker compose up -d ;;
esac
# Caddy reads its Caddyfile only at startup; pick up a newly written one.
if [ "$caddyfile_written" = "1" ]; then
        docker compose restart caddy > /dev/null 2>&1 || true
fi

echo ""
echo "=== Done ==="

public_base_url="${public_base_url:-$(env_get PUBLIC_URL)}"
case ",${profiles}," in *",caddy,"*) proxy_mode="Caddy (bundled)" ;; *) proxy_mode="" ;; esac
if [ -z "$proxy_mode" ]; then
        if [ "$(env_get COOKIE_SECURE)" = "false" ]; then proxy_mode="none (local testing)"; else proxy_mode="your own reverse proxy"; fi
fi
case ",${profiles}," in *",seeder,"*) seeder_on=1 ;; *) seeder_on=0 ;; esac
echo "Enabled options:"
echo "  Reverse proxy:          ${proxy_mode}"
download_summary="$(env_get DOWNLOAD_BASE_URL)"
echo "  Download base URL:      ${download_summary:-same address as the site}"
echo "  Mirror/torrent links:   $(env_get EXTERNAL_MIRRORS_ENABLED) (changeable in /admin/settings)"
echo "  VPN seeder:             $([ "$seeder_on" = "1" ] && echo enabled || echo off)"
echo ""
case ",${profiles}," in
*",caddy,"*)
        echo "The site is starting up behind Caddy. Give it a few seconds, then visit:"
        echo "  ${public_base_url:-https://<this-host-ip-or-domain>}"
        echo ""
        echo "Important: use https:// on the default port 443 -- do NOT add the"
        echo "app port (${http_port:-8080}) to the URL. Behind Caddy the app is reached"
        echo "only through Caddy's HTTPS; it is intentionally not exposed over plain"
        echo "HTTP on the network (signing in over http:// would loop the login,"
        echo "because the session cookie is HTTPS-only)."
        ;;
*)
        echo "The site is starting up. Give it a few seconds, then visit:"
        echo "  ${public_base_url:-http://localhost:${http_port:-8080}}"
        ;;
esac

echo ""
echo "New install? Visit /setup to create the administrator account -- there is"
echo "no default password to change, the account simply doesn't exist until you"
echo "create it there. (After that, /setup is gone and you sign in at /login.)"

incoming_abs="$(cd "$incoming_host_path" && pwd)"
echo ""
echo "Large files (ISOs etc.) go into the incoming folder on this host:"
echo "  ${incoming_abs}"
echo "for example from your workstation:"
echo "  rsync -avP --partial-dir=.rsync-partial ./my-image.iso $(id -un)@$(hostname -f 2>/dev/null || hostname):${incoming_abs}/"
echo "then import them from the release's Files page in /admin. Behind Cloudflare,"
echo "anything over about 100 MB must use this route: browser uploads are capped"
echo "at MAX_UPLOAD_BYTES ($(env_get MAX_UPLOAD_BYTES) bytes). See docs/IMPORT.md."

if [ "$seeder_on" = "1" ]; then
        echo ""
        seeder_print_webui
        echo ""
        if [ "$seeder_up_failed" = "1" ]; then
                echo "  !! The VPN container (gluetun) did not become healthy, so qBittorrent was"
                echo "  !! NOT started (nothing can leak). Check the VPN settings in .env and"
                echo "  !! 'docker compose logs gluetun', then: docker compose up -d"
        fi
        echo "Waiting for the VPN to come up to check that seeding traffic uses it..."
        wait_rounds=30
        if [ "$seeder_up_failed" = "1" ]; then
                wait_rounds=0
        fi
        seeder_wait_running "$wait_rounds" || true
        sleep 5
        # Fail closed (same as scripts/enable-seeder.sh): never leave the seeder
        # running without a passing check.
        if ! timeout 120 scripts/check-seeder-ip.sh; then
                seeder_stop_and_remove
                env_set COMPOSE_PROFILES "$(profiles_remove "$(env_get COMPOSE_PROFILES)" seeder)"
                echo "The seeder was stopped and removed, and 'seeder' was taken out of"
                echo "COMPOSE_PROFILES. Fix the VPN settings in .env, then run scripts/enable-seeder.sh."
        fi
fi
echo ""
echo "Installation complete."
